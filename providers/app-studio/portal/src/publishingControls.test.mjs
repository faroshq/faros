test('restores the Share trigger after confirmed disable and uses one production-surface polling transition', () => {
  const unpublishStart = app.indexOf('async function unpublishCurrentProject')
  const unpublishEnd = app.indexOf('async function grantCurrentProjectAccess', unpublishStart)
  assert.ok(unpublishStart >= 0 && unpublishEnd > unpublishStart)
  const unpublish = app.slice(unpublishStart, unpublishEnd)
  assert.match(unpublish, /let disableSucceeded = false/)
  assert.match(unpublish, /publishingActionBusy\.value = false[\s\S]*if \(disableSucceeded\) closeShareDialog\(\)/)
  assert.doesNotMatch(unpublish, /shareDialogOpen\.value = false/)

  assert.match(app, /const productionSurfaceActive = computed\(\(\) => productionSettingsVisible\.value \|\| shareDialogOpen\.value\)/)
  assert.match(app, /if \(releasePipeline\.value\.transitional\)/)
  assert.match(app, /releaseTakingLonger\.value \? PROMOTION_POLL_MAX_DELAY_MS : promotionPollDelay\(0\)/)
  const watcherStart = app.indexOf('watch(\n  () => [productionSurfaceActive.value')
  const watcherEnd = app.indexOf('\n\n onBeforeUnmount', watcherStart)
  assert.ok(watcherStart >= 0)
  const watcher = app.slice(watcherStart, watcherEnd > watcherStart ? watcherEnd : watcherStart + 1800)
  assert.match(watcher, /surfaceOrProjectChanged/)
  assert.match(watcher, /clearPromotionPoll\(\)/)
  assert.match(watcher, /clearPublishingPoll\(\)/)
  assert.doesNotMatch(watcher, /kind === 'publishing'/)
  const openStart = app.indexOf('function openShareDialog')
  const openEnd = app.indexOf('function closeShareDialog', openStart)
  assert.ok(openStart >= 0 && openEnd > openStart)
  assert.doesNotMatch(app.slice(openStart, openEnd), /loadPromotion|loadPublishing/)

  const settingsStart = app.indexOf('function openProductionSettingsFromShare')
  const settingsEnd = app.indexOf('function resetWorkbench', settingsStart)
  assert.ok(settingsStart >= 0 && settingsEnd > settingsStart)
  const settingsHandler = app.slice(settingsStart, settingsEnd)
  assert.match(settingsHandler, /shareDialogOpen\.value = false/)
  assert.match(settingsHandler, /projectSettingsPane\.value = 'production'/)
  assert.match(settingsHandler, /openBuiltInWorkbenchTab\('settings'\)/)
  assert.match(settingsHandler, /productionSettingsPaneRef\.value\?\.focus\(\)/)
  assert.doesNotMatch(settingsHandler, /shareButtonRef/)

  const closeStart = app.indexOf('function closeShareDialog')
  const closeEnd = app.indexOf('function openProductionSettingsFromShare', closeStart)
  assert.ok(closeStart >= 0 && closeEnd > closeStart)
  const closeHandler = app.slice(closeStart, closeEnd)
  assert.match(closeHandler, /shareDialogOpen\.value = false[\s\S]*if \(!productionSettingsVisible\.value\)/)
  assert.doesNotMatch(closeHandler, /kind !== 'production'/)
})

